    private fun prefs(ctx: Context) =
        ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    /** 実際に使う文面。保存が無ければ中国語の既定。 */
    fun current(ctx: Context): String =
        prefs(ctx).getString(KEY, null) ?: CHINESE

    fun save(ctx: Context, text: String) {
        prefs(ctx).edit().putString(KEY, text).apply()
    }

    /** 中国語の既定に戻す（保存を消すだけ）。 */
    fun resetToChinese(ctx: Context) {
        prefs(ctx).edit().remove(KEY).apply()
    }

    fun resetToEnglish(ctx: Context) = save(ctx, ENGLISH)

    fun resetToTerms(ctx: Context) = save(ctx, TERMS)

    /** 設定画面に出す、今どれが効いているかの表示。 */
    fun label(ctx: Context): String = when (current(ctx)) {
        CHINESE -> "既定（中国語）"
        ENGLISH -> "既定（英語）"
        TERMS -> "既定（専門用語）"
        else -> "カスタム"
    }
